with cte_parent as (
    select
        p.pid,
        p.product_type_id,
        p.name,
        p.url,
        p.origin,
        p.thickness,
        p.material,
        p.weave,
        p.weave_feature,
        p.color,
        p.brand,
        --p.imageName,
        --p.imageType,
        --p.internalName,
        p.category,
        p.min_price,
        p.max_price,
        p.availability,
        p.aggregate,
        p.clearance,
        p.long_description,
        p.shopbyroom,
        p.dw_insert_timestamp
    from public.rugs_usa_parent as p
),

cte_variant as (
    select
        v.pid,
        v.variant,
        v.actual_size,
        v.weave_feature,
        v.weave_cat,
        v.size_grp,
        v.shipping_size,
        v.shape,
        v.weight,
        v.price,
        v.msrp,
        v.stock_level,
        v.depletion_level,
        v.low_stock,
        v.estimated_delivery_date,
        v.this_isd_range,
        v.status,
        v.origin,
        v.new_arrival,
        --v.stockMsg,
        --v.stockeddMsg,
        v.other_stock_core,
        v.other_stock_compass,
        v.dw_insert_timestamp
    from public.rugs_usa_variant as v
)

select distinct
    concat(p.pid, v.variant) as product_pk,
    p.pid,
    v.variant,
    p.product_type_id,
    p.name,
    p.url,
    coalesce(v.origin, p.origin) as origin,
    p.thickness,
    p.material,
    p.weave,
    coalesce(v.weave_feature, p.weave_feature) as weave_feature,
    p.color,
    p.brand,
    --p.imagename,
    --p.imagetype,
    --p.internalname,
    p.category,
    p.min_price,
    p.max_price,
    p.availability,
    p.aggregate,
    p.clearance,
    --p.long_description, --commenting out since it's such a long string
    p.shopbyroom,
    p.dw_insert_timestamp as parent_dw_insert_timestamp,
    v.actual_size,
    v.weave_cat,
    v.size_grp,
    v.shipping_size,
    v.shape,
    v.weight,
    v.price,
    v.msrp,
    v.stock_level,
    v.depletion_level,
    v.low_stock,
    v.estimated_delivery_date,
    v.this_isd_range,
    v.status,
    v.new_arrival,
    --v.stockmsg,
    --v.stockeddsg,
    v.other_stock_core,
    v.other_stock_compass,
    v.dw_insert_timestamp as variant_dw_insert_timestamp
from cte_parent as p
left outer join cte_variant as v on p.pid = v.pid
